package main

import (
	"os"
	"strings"
	"time"
)

// This optional control path stops new offered work, then uses the existing
// bounded send/receipt drain, reader cutover and complete journal finalization.
func watchControllerStop(path string, done <-chan struct{}, stop func()) {
	ticker := time.NewTicker(100 * time.Millisecond)
	defer ticker.Stop()
	for {
		select {
		case <-done:
			return
		case <-ticker.C:
			if _, err := os.Stat(path); err == nil {
				stop()
				return
			}
		}
	}
}

// xorshift64* emits a deterministic, high entropy printable corpus. The seed
// and every generated byte are independently checked by the C++ disk oracle.
func makePayload(cid string, size int, pattern string) string {
	prefix := cid + "|"
	if pattern == "repeat" {
		return prefix + strings.Repeat("x", size-len(prefix))
	}
	state := uint64(14695981039346656037)
	for i := 0; i < len(cid); i++ {
		state ^= uint64(cid[i])
		state *= 1099511628211
	}
	if state == 0 {
		state = 1
	}
	const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
	b := make([]byte, size)
	copy(b, prefix)
	for i := len(prefix); i < size; i++ {
		state ^= state >> 12
		state ^= state << 25
		state ^= state >> 27
		b[i] = alphabet[(state*2685821657736338717)>>58]
	}
	return string(b)
}
